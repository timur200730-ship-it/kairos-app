    // Вспомогательный метод: получить приветствие и вопрос под текущий час
    getCurrentGreeting: function() {
        const hour = new Date().getHours();
        let block = this.greetings.morning;
        if (hour >= 5 && hour < 12) block = this.greetings.morning;
        else if (hour >= 12 && hour < 18) block = this.greetings.afternoon;
        else if (hour >= 18 && hour < 23) block = this.greetings.evening;
        else block = this.greetings.night;

        // Выбираем фразу детерминированно по дню месяца, чтобы она не прыгала при каждом клике
        const dayIndex = new Date().getDate();
        return {
            period: block.period,
            icon: block.icon,
            title: block.titles[dayIndex % block.titles.length],
            question: block.questions[dayIndex % block.questions.length]
        };
    },

    // Вспомогательный метод: случайный живой отклик при выполнении
    getRandomFeedback: function(type = 'fullDone') {
        const list = this.feedback[type] || this.feedback.fullDone;
        return list[Math.floor(Math.random() * list.length)];
    }
